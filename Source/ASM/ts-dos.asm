RAWPAK_NAME_MAIN:
                DEFB "ZUMAMAIN.PAK", 0
RAWPAK_NAME_BOOT:                               ; HOBETA WC loader в корне SD (для Quit)
                DEFB "BOOT.$C", 0
RAWPAK_BOOT_SIZE EQU 31761
RAWPAK_BOOT_SECTORS EQU (RAWPAK_BOOT_SIZE + 511) / 512

; Клод: удалены RawPak_OpenRoot (MBR/BPB), RawPak_FindByName/FindEntryInCur,
; LFN/8.3 (RawPak_StoreLfn/Build83/NameMatch), обход FAT и таблица кусков файла
; (RawPak_FatNext/BuildRunTable/CurrentLbaRegs): это теперь делает драйвер.

; Прочитать путь активной панели Wild Commander из page #F7:
;   #F7:#1000 left path, #F7:#2000 right path, #F7:#1FFC active marker.
; Path format — "N:\dir\subdir\#FF". N игнорируется (читается SD), но
; сохраняется для diagnostics; prefix валидируется до прохода по каталогам.
; Выход: CF=1 — путь без префикса скопирован в RawPak_WcPathBuf (до #FF);
;        CF=0, если WC path отсутствует/битый. Оставляет #F7 в slot 2.
RawPak_ReadWcPath:
                LD   A, WC_RPPG
                SetPage2_A
                LD   HL, #8000 + WC_RAPNL
                LD   A, (HL)
                CP   #41
                JR   Z, .left
                CP   #42
                JR   NZ, .fail
                LD   HL, #8000 + WC_RRPNL
                JR   .havePanel
.left:          LD   HL, #8000 + WC_RLPNL
.havePanel:     LD   A, (HL)
                CP   '0'
                JR   C, .fail
                CP   '9' + 1
                JR   NC, .fail
                LD   (RawPak_WcDevice), A
                INC  HL
                LD   A, (HL)
                CP   ':'
                JR   NZ, .fail
                INC  HL
                LD   A, (HL)
                CP   '\'
                JR   NZ, .fail
                INC  HL
                LD   DE, RawPak_WcPathBuf
                LD   B, WC_PATH_MAX-1
.copy:          LD   A, (HL)
                INC  HL
                CP   #FF
                JR   Z, .term
                LD   (DE), A
                INC  DE
                DJNZ .copy
.fail:          OR   A
                RET
.term:          LD   (DE), A
                SCF
                RET

; HL указывает на WC path component. Скопировать его в RawPak_TargetName,
; uppercase и zero-terminate. Возвращает HL на next component (или #FF),
; CF=1 при успехе.
RawPak_CopyWcComponent:
                LD   DE, RawPak_TargetName
                LD   B, 63
.loop:          LD   A, (HL)
                CP   #FF
                JR   Z, .done
                CP   '\'
                JR   Z, .slash
                OR   A
                JR   Z, .fail
                CALL RawPak_Upcase
                LD   (DE), A
                INC  DE
                INC  HL
                DJNZ .loop
.fail:          OR   A
                RET
.slash:         INC  HL
.done:          XOR  A
                LD   (DE), A
                LD   A, D
                CP   RawPak_TargetName >> 8
                JR   NZ, .ok
                LD   A, E
                CP   RawPak_TargetName & #FF
                JR   Z, .fail
.ok:            SCF
                RET

; Стек обхода каталогов (LIFO, Fat_DfsFind). Entries — 4-byte start clusters.
RawPak_DirStackPush:                            ; HL -> 4-byte cluster; игнорируется при полном стеке
                LD   A, (RawPak_DirStackCnt)
                CP   RAWPAK_DIRSTACK_MAX
                RET  NC
                PUSH HL
                LD   L, A
                LD   H, 0
                ADD  HL, HL
                ADD  HL, HL                      ; HL = cnt * 4
                LD   DE, RawPak_DirStack
                ADD  HL, DE
                EX   DE, HL                      ; DE = dest slot
                POP  HL                          ; HL = src cluster
                LD   BC, 4
                LDIR
                LD   A, (RawPak_DirStackCnt)
                INC  A
                LD   (RawPak_DirStackCnt), A
                RET

RawPak_DirStackPop:                             ; CurClus = top; CF=1 если empty
                LD   A, (RawPak_DirStackCnt)
                OR   A
                JR   Z, .empty
                DEC  A
                LD   (RawPak_DirStackCnt), A
                LD   L, A
                LD   H, 0
                ADD  HL, HL
                ADD  HL, HL
                LD   DE, RawPak_DirStack
                ADD  HL, DE                      ; HL = src slot
                LD   DE, RawPak_CurClus
                LD   BC, 4
                LDIR
                OR   A                           ; CF=0 (A = new count, не wrap до CF)
                RET
.empty:        SCF
                RET

; A = uppercase(A) для ASCII a-z; остальные bytes без изменений.
RawPak_Upcase:  CP   'a'
                RET  C
                CP   'z' + 1
                RET  NC
                SUB  #20
                RET

; ============================================================================
; OVL_ProbeBoot (Этап 1 загрузчика Quit) — найти BOOT.$C в корне SD и прочитать его
; целиком в страницы QUIT_BOOT_PAGE0/1, пока игра ещё жива. Вызывается через
; резидентный трамплин ProbeBootHobeta (slot3 = LOADER_OVL_PAGE уже выставлен).
; Клод: читает FAT32-драйвер (FIND + READ_AT), поэтому BOOT.$C может быть и
; фрагментирован; стаб выхода (quit_loader_stub.asm) только копирует его из этих
; страниц в окно WC, своего чтения SD у него больше нет.
;   Boot_Found = 1, если найден, размер RAWPAK_BOOT_SIZE и прочитан, иначе 0.
;   Boot_Size  = размер в байтах (4), Boot_Hdr = первые 32 байта (HOBETA-заголовок).
; ============================================================================
OVL_ProbeBoot:
                XOR  A
                LD   (Boot_Found), A
                CALL ZiFi_Init                  ; CF=1 — том готов
                JR   NC, .pbDone
                XOR  A
                LD   (Fat_OpenId), A            ; FIND выберет BOOT.$C вместо пака
                FATCALL FAT32_SET_ROOT
                OR   A
                JR   NZ, .pbFail
                XOR  A
                LD   HL, RAWPAK_NAME_BOOT
                CALL Fat_FindName               ; CF=1 — ошибка, Z — нет; DE:HL = размер
                JR   C, .pbDone
                JR   Z, .pbDone
                LD   A, D
                OR   E
                JR   NZ, .pbDone
                LD   BC, RAWPAK_BOOT_SIZE
                OR   A
                SBC  HL, BC
                JR   NZ, .pbDone
                LD   A, FAT_ID_BOOT
                LD   (Fat_OpenId), A
                LD   HL, RAWPAK_BOOT_SIZE
                LD   (Boot_Size + 0), HL
                LD   HL, 0
                LD   (Boot_Size + 2), HL
                LD   (RawPak_LogCur), HL
                LD   C, QUIT_BOOT_PAGE0         ; file[#0000..#3FFF]
                LD   HL, 0
                LD   B, 32
                CALL Fat_ReadSectors
                JR   C, .pbDone
                LD   C, QUIT_BOOT_PAGE1         ; file[#4000..], последний сектор неполный
                LD   HL, 0
                LD   B, RAWPAK_BOOT_SECTORS - 32
                CALL Fat_ReadSectors
                JR   C, .pbDone
                LD   A, QUIT_BOOT_PAGE0
                SetPage2_A
                LD   HL, #8000                  ; заголовок — для F12-дампа
                LD   DE, Boot_Hdr
                LD   BC, 32
                LDIR
                LD   A, 1
                LD   (Boot_Found), A
.pbDone:        JP   ZiFi_Done
.pbFail:        CALL Fat_Fail
                JR   .pbDone

; ============================================================================
; RawPak_ReadOneLogicalIX — прочитать логический сектор файла RawPak_LogCur в (IX).
; IX — в окне slot 2 (#8000..#BE00), страница — та, что сейчас в slot 2.
; Клод: через Fat_ReadSectors (FILEX READ_AT). Двигает RawPak_LogCur только после
; успешного чтения. Выход: CF=1 — ошибка. IX сохраняется.
; ============================================================================
RawPak_ReadOneLogicalIX:
                PUSH IX
                POP  HL
                LD   A, H
                SUB  #80
                LD   H, A                       ; HL = смещение в странице slot 2
                GetPage2
                LD   C, A
                LD   B, 1
                JP   Fat_ReadSectors

; Compatibility entry для callers, которым исторически требовался sector retry.
; Повторы обмена — внутри порта SD-ZC драйвера.
RawPak_ReadOneLogicalIX_Retry:
                JP   RawPak_ReadOneLogicalIX    ; сохраняет прежний symbol/API без nested retry

RawPak_TargetName:     DEFS 64        ; target name (uppercased, zero-term)
RawPak_CheckSize:      DEFB 1         ; 1=match name+EXPECTED_PAK_SIZE, 0=только name (Fat_DfsFind)
RawPak_CurClus:        DEFS 4         ; кластер каталога, снятый со стека обхода
RawPak_LogCur:         DEFW 0         ; текущий file logical sector для Fat_ReadSectors
RawPak_StgPage:        DEFB 0         ; staging page cursor для SD/FT phases
RawPak_TrkPagesLeft:   DEFB 0         ; Track V2 sample pages left to load
RawPak_TrkPagePtr:     DEFW 0         ; pointer into VDC_TrackLoadPages
RawPak_ReadbackBuf:    DEFS 16        ; probe FT RAM_G readback для preview commit guard
RawPak_VerifySrc:      DEFW 0
RawPak_VerifyRamL:     DEFW 0
RawPak_VerifyRamH:     DEFB 0

; Стек обхода каталогов в поисках ZUMALVL.PAK. DirStack — DFS frontier ожидающих
