; ZiFi_LevelTOC — 20-byte buffer с TOC entry активного level.
; Layout (little-endian words):
;   +0  bg_off       (sectors; 0xFFFF = отсутствует)
;   +2  bg_size
;   +4  pal_off
;   +6  pal_size
;   +8  track_off
;   +10 track_size
;   +12 title_off
;   +14 title_size
;   +16 preview_off
;   +18 preview_size
ZiFi_LevelTOC:    DEFS 20

