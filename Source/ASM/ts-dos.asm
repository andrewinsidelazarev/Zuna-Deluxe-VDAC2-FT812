; ts-dos.asm — загрузчик паков игры (ZUMAMAIN/ZUMALVL/ZUMAAUD/ZUMASND.PAK) и
; BOOT.$C для выхода в WC.
;
; Клод: SD-карта и FAT32 — через самостоятельный FAT32-драйвер
; (Source/ThirdParty/FAT32, переходник fat32_adapter.asm). Прежний собственный
; путь — прямые CMD17 (sd_zc.asm), разбор MBR/BPB, обход FAT, LFN и своя таблица
; кусков файла (RawPak_BuildRunTable) — удалён: драйвер монтирует том
; (MBR/EBR/том от LBA 0), ищет записи по LFN/8.3 без учёта регистра, проверяет
; цепочки и читает по смещению в файле (FILEX READ_AT) с вехами цепочки и кэшем
; сектора FAT. Имена ZiFi_*/RawPak_* сохранены: их зовут сцены, трамплины
; loader_resident.asm и тестовый стенд Source/OTHER.
;
; Файл собирается в SLOT 3 / PAGE #40 loader overlay (см. main.asm) и mapped только
; во время загрузок. Track V2 reader/page tables и VDC_ReadSampleAtHL живут в
; loader_resident.asm: они нужны каждый кадр. Именованные entry points доступны
; через resident trampolines, которые вызывают OVL_* ниже.
;
; Сеанс загрузки: ZiFi_Init (DI, шина SPI свободна от FT812, монтирование при
; первом вызове) … ZiFi_Done (EI). Внутри сеанса: открыть пак (ZiFi_*PakOpen),
; читать логические секторы файла с RawPak_LogCur (Fat_ReadSectors или
; RawPak_ReadOneLogicalIX).

WC_RPPG         EQU #F7
WC_RLPNL        EQU #1000
WC_RRPNL        EQU #2000
WC_RAPNL        EQU #2000-4
WC_PATH_MAX     EQU 160

