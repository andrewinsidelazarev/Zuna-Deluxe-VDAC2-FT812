                LD   HL, RAWPAK_NAME_AUDIO
                JR   ZiFi_OpenPak
ZiFi_SoundPakOpen:
                LD   A, FAT_ID_SOUND
                LD   HL, RAWPAK_NAME_SOUND
                JR   ZiFi_OpenPak
ZiFi_MainPakOpen:
                LD   A, FAT_ID_MAIN
                LD   HL, RAWPAK_NAME_MAIN
ZiFi_OpenPak:
                CALL Fat_OpenPak                ; CF=0 — выбран
                CCF
                RET

OVL_LoadMainPack:
                CALL ZiFi_Init
                RET  NC
                LD   A, 100
                CALL BootProgressSetA
                CALL ZiFi_MainPakOpen
                JR   NC, .fail
                LD   A, 105
                CALL BootProgressSetA
                LD   HL, MainPakPageTable
                LD   A, MAIN_PAK_PAGE_COUNT
                LD   (MainPakPagesLeft), A
.pageLoop:      LD   A, (MainPakPagesLeft)
                OR   A
                JR   Z, .done
                LD   A, (HL)
                INC  HL
                LD   (MainPakTargetPage), A
                LD   E, (HL)
                INC  HL
                LD   D, (HL)
                INC  HL
                PUSH HL
                LD   (RawPak_LogCur), DE
                ; Клод: страница читается четырьмя вызовами READ_AT по 8 секторов
                ; (4 КиБ) вместо 32 посекторных: тик анимации загрузки — как прежде,
                ; каждые 8 секторов.
                LD   HL, 0                      ; смещение в странице
.chunkLoop:     PUSH HL
                LD   A, (MainPakTargetPage)
                LD   C, A
                LD   B, 8
                CALL Fat_ReadSectors
                JR   C, .readFail
                CALL BootLoadingTick
                POP  HL
                LD   DE, 8 * 512
                ADD  HL, DE
                BIT  6, H                       ; #4000 — страница заполнена
                JR   Z, .chunkLoop
                CALL BootProgressInc
                POP  HL
                LD   A, (MainPakPagesLeft)
                DEC  A
                LD   (MainPakPagesLeft), A
                JR   .pageLoop
.done:          CALL ZiFi_Done
                SCF
                RET
.readFail:      POP  HL
                POP  HL
.fail:          CALL ZiFi_Done
                OR   A
                RET

MainPakTargetPage: DEFB 0
MainPakPagesLeft:  DEFB 0

; ZiFi_PakReadToc — прочитать TOC sector (sec 1), скопировать entry [A] в
; ZiFi_LevelTOC.
; Вход : A = level index (0..21)
; Выход: ZiFi_LevelTOC заполнен 20 bytes; CF=1 ok, CF=0 отсутствующий slot или
;        ошибка чтения.
;        Pak уже должен быть открыт (сначала вызвать ZiFi_PakOpen).
; Клобает: AF, BC, DE, HL
ZiFi_PakReadToc:
                PUSH AF
                ; read TOC = file logical sector 1 в buffer page.
                LD   A, ZIFI_BUFFER_PAGE
                SetPage2_A
                LD   IX, #8000
                LD   HL, 1
                LD   (RawPak_LogCur), HL
                CALL RawPak_ReadOneLogicalIX
                JR   C, .ReadErr                ; Клод: ошибка чтения — не разбирать старый буфер
                ; map buffer page в slot 2, чтобы читать его
                LD   A, ZIFI_BUFFER_PAGE
                SetPage2_A
                ; HL = #8000 + (level_idx * 20)
                POP  AF
                LD   H, 0
                LD   L, A
                ; HL = level_idx
                ; умножить HL × 20:
                ADD  HL, HL              ; ×2
                ADD  HL, HL              ; ×4
                LD   D, H : LD E, L
                ADD  HL, HL              ; ×8
                ADD  HL, HL              ; ×16
                ADD  HL, DE              ; ×20
                LD   DE, #8000
                ADD  HL, DE              ; HL = entry source
                LD   DE, ZiFi_LevelTOC
                LD   BC, 20
                LDIR
                ; проверить bg_off (первое word): 0xFFFF значит slot отсутствует
                LD   HL, (ZiFi_LevelTOC)
                LD   A, H
                CP   #FF
                JR   NZ, .Exists
                LD   A, L
                CP   #FF
                JR   Z, .Absent
.Exists:
                SCF
                RET
.ReadErr:       POP  AF
.Absent:        OR   A
                RET

; Клод: удалены ZiFi_SkipSectors16 и ZiFi_StreamSection (потоковое чтение через
; старый LOAD512 и запись в RAM_G): вызовов не осталось.

; OVL_GS_InitAndStartMenuMusic — обнаружить General Sound, один раз загрузить
; ZUMAAUD.PAK, затем запустить module как menu/level-select/more-games music.
OVL_GS_InitAndStartMenuMusic:
                LD   A, (GS_MenuMusicLoaded)
                OR   A
                JR   Z, .needLoad
                JP   GS_PlayMenuMusic
.needLoad:      CALL GS_Detect
                JR   C, .gsDetected
                RET
.gsDetected:    LD   A, 1
                LD   (GS_Present), A
                LD   (GS_MenuMusicHandle), A
                XOR  A
                LD   (GS_SfxLoaded), A
                CALL GS_QueryRamPages
                CALL GS_InitFxMixer
                CALL ZiFi_Init
                JR   NC, .sdFail
                CALL ZiFi_AudioPakOpen
                JR   NC, .sdDoneFail
                CALL GS_CacheAudioPakToRam
                JR   NC, .sdDoneFail
                CALL ZiFi_Done
                DI
                LD   A, #30                         ; Load Module
                CALL GS_SendCommandOverlay
                RET  NC
                LD   A, #D1                         ; Open Stream
                CALL GS_SendCommandOverlay
                RET  NC
                CALL GS_StreamAudioCacheToDevice    ; стрим RAM->GS + тик прогресс-бара
                JR   NC, .closeFail
                LD   A, #D2                         ; Close Stream
                CALL GS_SendCommandOverlay
                RET  NC
                CALL GS_ReadHandleMaybe
                LD   A, 1
                LD   (GS_MenuMusicLoaded), A
                CALL GS_PostLoadSettle              ; пауза перед командой включения музыки
                JP   GS_PlayMenuMusic
.closeFail:     LD   A, #D2
                CALL GS_SendCommandOverlay
                RET
.sdDoneFail:    CALL ZiFi_Done
.sdFail:        RET

GS_ClearState:
                XOR  A
                LD   (GS_Present), A
                LD   (GS_MenuMusicLoaded), A
                LD   (GS_MenuMusicHandle), A
                LD   (GS_MenuMusicPlaying), A
                LD   (GS_SfxLoaded), A
                LD   (GS_RamPages), A
                RET

GS_Detect:
