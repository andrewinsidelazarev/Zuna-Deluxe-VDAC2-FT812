                include "audio_pak_size.inc"    ; точный stream size ZUMAAUD.PAK для GS menu music
                include "sound_pak_size.inc"    ; sound IDs ZUMASND.PAK и точный PCM pack size
                include "main_pak_table.inc"    ; ZUMAMAIN.PAK page load table
                include "fat32_adapter.asm"     ; Клод: FAT32-драйвер вместо sd_zc.asm

; ---------------------------------------------------------------------
; ZiFi_Init — начать сеанс работы с SD: DI, slot 0 = TSLib, шина SPI отдана SD.
; Клод: карта инициализируется и том монтируется драйвером один раз за запуск
; игры (Fat_EnsureMounted) и заново — после ошибки драйвера.
;   CF=1 при успехе, CF=0 при ошибке карты/тома. После вызова в любом случае
;   нужно вызвать ZiFi_Done.
ZiFi_Init:
                DI
                ; FT812 и SD на ОДНОЙ SPI-шине Z-Controller (рег #77). Перед началом
                ; SD-сессии ЯВНО снимаем CS FT812 (#77 = SPI_FT_CS_OFF = #03), иначе,
                ; если перед этим по шине работал FT812 (boot loading screen), он
                ; остаётся владельцем шины и первое SD-обращение срывается.
                LD   BC, #0077
                LD   A, #03
                OUT  (C), A
                LD   BC, #0057
                LD   A, #FF
                OUT  (C), A
                LD   A, TSLibPage
                SetPage0_A                     ; slot 0 вернуть на штатную TSLib page до SD-session
                CALL Fat_EnsureMounted         ; CF=0 — том готов
                CCF                            ; публичный ZiFi-контракт наоборот: CF=1 — успех
                RET

; ZiFi_Done — восстановить TSLib в slot 0, EI.
ZiFi_Done:
                LD   BC, #0077
                LD   A, #03
                OUT  (C), A
                LD   BC, #0057
                LD   A, #FF
                OUT  (C), A
                LD   A,  TSLibPage
                SetPage0_A
                EI
                RET

