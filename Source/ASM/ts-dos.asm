; Клод: кэш читается кусками по 8 секторов (Fat_ReadSectors, READ_AT) вместо
; посекторных вызовов; прогресс как прежде: деление бара в начале страницы, тик
; анимации после каждых 8 секторов. Чтение — с начала пака явно (RawPak_LogCur=0):
; прежде позиция бралась из начального значения переменной, и повторная загрузка
; музыки из меню читала бы с чужой позиции.
GS_CacheAudioPakToRam:
                LD   HL, EXPECTED_AUDIO_PAK_SECTORS
                LD   (GS_AudioCacheSecsLeft), HL
