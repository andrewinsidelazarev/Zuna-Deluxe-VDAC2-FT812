; (#BB/#B3), а FT-рисование — на SPI (#77/#57); BootBusOwner=0 между секторами
; (GS_StreamBufferDE отдаёт его в .ok). Каждые 256 секторов двигаем бар на 1px
; (в рамках бюджета фазы «музыка» 5..60), каждые 32 — перерисовка (анимация жива,
; экран не «висит» ~3 c стрима). Полностью сохраняет регистры вызывающего.
GS_StreamProgressTick:
                PUSH HL
                PUSH DE
                PUSH BC
                PUSH AF
                LD   A, (GS_StreamTick)
                INC  A
                LD   (GS_StreamTick), A
                JR   NZ, .noAdv                       ; перенос 255->0 каждые 256 секторов
                CALL BootProgressIncNoDraw
.noAdv:         LD   A, (GS_StreamTick)
                AND  #1F
                JR   NZ, .done                        ; перерисовка каждые 32 сектора
                CALL BootLoadingTickSafe
                LD   A, (GS_AudioStreamPage)          ; восстановить slot2 на текущую стрим-страницу
                SetPage2_A
.done:          POP  AF
                POP  BC
                POP  DE
                POP  HL
                RET
GS_StreamTick:  DEFB 0

GS_StreamBufferDE:
                LD   A, 1
                LD   (BootBusOwner), A
                LD   A, D
                OR   E
                JR   Z, .ok
.loop:          LD   A, (HL)
                INC  HL
                CALL GS_SendDataOverlay
                RET  NC
                DEC  DE
                LD   A, D
                OR   E
                JR   NZ, .loop
.ok:            XOR  A
                LD   (BootBusOwner), A
                SCF
                RET

GS_SendCommandOverlay:
                LD   BC, GS_PORT_CMD
                OUT  (C), A
                LD   HL, GS_WAIT_TIMEOUT
.wcmd:          IN   A, (C)
                RRCA
                JR   NC, .ok
                DEC  HL
                LD   A, H
                OR   L
                JR   NZ, .wcmd
                OR   A
                RET
.ok:            SCF
                RET

; Отправка байта данных в GS. КАК В WC (gsplayer GSLOAD/TE0): СНАЧАЛА ждём, пока
; в FIFO освободится место (bit7 статуса #BB сброшен), ПОТОМ пишем байт в #B3.
; Раньше было наоборот (писали, потом ждали) — на эмуляторе прокатывало, но на
; реальном MultiSound запись без проверки места переполняет FIFO → байты теряются
; → стрим модуля бьётся и загрузка не завершается. Байт сохраняем в E на время ожидания.
GS_SendDataOverlay:
                PUSH HL
                PUSH DE
                LD   E, A                       ; сохранить байт данных
                LD   BC, GS_PORT_CMD            ; #BB — статус
                LD   HL, GS_WAIT_TIMEOUT
.wdat:          IN   A, (C)
                RLCA                            ; bit7 -> CF (1 = FIFO полон/не готов)
                JR   NC, .ready                 ; bit7=0 -> есть место
                DEC  HL
                LD   A, H
                OR   L
                JR   NZ, .wdat
                POP  DE
                POP  HL
                XOR  A
                LD   (BootBusOwner), A
                OR   A                          ; таймаут -> CF=0
                RET
.ready:         LD   A, E
                LD   BC, GS_PORT_DATA           ; #B3 — данные
                OUT  (C), A                     ; место есть -> пишем
                POP  DE
                POP  HL
                SCF
                RET

GS_ReadDataWaitOverlay:
                LD   BC, GS_PORT_CMD
                LD   HL, GS_WAIT_TIMEOUT
.wait:          IN   A, (C)
                RLCA
                JR   C, .ready
                DEC  HL
                LD   A, H
                OR   L
                JR   NZ, .wait
                OR   A
                RET
.ready:         LD   BC, GS_PORT_DATA
                IN   A, (C)
                SCF
                RET

