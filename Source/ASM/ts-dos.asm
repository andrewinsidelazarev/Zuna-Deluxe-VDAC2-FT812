                LD   A, H
                OR   L
                JR   Z, .done
                CALL BootProgressIncNoDraw
                LD   HL, 0                      ; смещение в странице
.chunk:         PUSH HL
                LD   HL, (GS_AudioCacheSecsLeft)
                LD   B, 8
                LD   A, H
                OR   A
                JR   NZ, .full
                LD   A, L
                CP   B
                JR   NC, .full
                LD   B, L                       ; хвост пака короче 8 секторов
.full:          LD   E, B
                LD   D, 0
                OR   A
                SBC  HL, DE
                LD   (GS_AudioCacheSecsLeft), HL
                POP  HL
                PUSH HL
                LD   A, (GS_AudioCachePage)
                LD   C, A
                CALL Fat_ReadSectors            ; последний сектор пака неполный — принимается
                POP  HL
                JR   C, .err
                CALL BootLoadingTickSafe
                LD   DE, 8 * 512
                ADD  HL, DE
                LD   A, (GS_AudioCacheSecsLeft + 0)
                LD   C, A
                LD   A, (GS_AudioCacheSecsLeft + 1)
                OR   C
                JR   Z, .done
                BIT  6, H                       ; #4000 — страница заполнена
                JR   Z, .chunk
.nextPage:      LD   A, (GS_AudioCachePage)
                INC  A
                LD   (GS_AudioCachePage), A
                JR   .page
.done:          SCF
                RET
.err:           OR   A
                RET

