; ZiFi_PakReadToc — прочитать TOC sector (sec 1), скопировать entry [A] в
; ZiFi_LevelTOC.
; Вход : A = level index (0..21)
; Выход: ZiFi_LevelTOC заполнен 20 bytes; CF=1 ok, CF=0 отсутствующий slot.
;        Pak уже должен быть открыт (сначала вызвать ZiFi_PakOpen).
; Клобает: AF, BC, DE, HL
ZiFi_PakReadToc:
                PUSH AF
                ; read TOC = file logical sector 1, напрямую через LBA (без FAT walk).
                LD   A, ZIFI_BUFFER_PAGE
                SetPage2_A
                LD   IX, #8000
                LD   HL, 1
                LD   (RawPak_LogCur), HL
                CALL RawPak_ReadOneLogicalIX
                ; map buffer page в slot 2, чтобы читать его
                LD   A, ZIFI_BUFFER_PAGE
                SetPage2_A
                ; HL = #8000 + (level_idx * 20)
                POP  AF
                LD   H, 0
                LD   L, A
                ; HL = level_idx
                ; умножить HL × 20:
                ADD  HL, HL              ; ×2
                ADD  HL, HL              ; ×4
                LD   D, H : LD E, L
                ADD  HL, HL              ; ×8
                ADD  HL, HL              ; ×16
                ADD  HL, DE              ; ×20
                LD   DE, #8000
                ADD  HL, DE              ; HL = entry source
                LD   DE, ZiFi_LevelTOC
                LD   BC, 20
                LDIR
                ; проверить bg_off (первое word): 0xFFFF значит slot отсутствует
                LD   HL, (ZiFi_LevelTOC)
                LD   A, H
                CP   #FF
                JR   NZ, .Exists
                LD   A, L
                CP   #FF
                JR   Z, .Absent
.Exists:
                SCF
                RET
.Absent:        OR   A
                RET

; ZiFi_SkipSectors16 — пропустить HL (16-bit) sectors вперёд.
; Не использовать LOADNON для больших seeks: свежий host dump 111 показал, что
; loader застревает сразу после TOC при seek L02 bg_off=#01F0 через LOADNON.
; Чтение и discard через LOAD512 медленнее, но использует тот же проверенный data path,
; что TOC/background reads.
;   Вход : HL = count
;   Выход: position продвинута
ZiFi_SkipSectors16:
.Loop:          LD   A, H
                OR   L
                RET  Z
                LD   A, H
                OR   A
                JR   NZ, .Full
                LD   A, L
                CP   32
                JR   NC, .Full
                LD   B, L
                LD   C, ZIFI_BUFFER_PAGE
                LD   HL, #0000
                JP   ZiFi_Load512
.Full:
                PUSH HL
                LD   B, 32
                LD   C, ZIFI_BUFFER_PAGE
                LD   HL, #0000
                CALL ZiFi_Load512
                POP  HL
                RET  C
                LD   DE, -32
                ADD  HL, DE
                JR   .Loop

; ZiFi_StreamSection — прочитать N sectors из pack и записать в FT812 RAM_G
; 16384-byte chunks (по 32 sectors).
;   Вход : DE = total sectors to read (для наших sections обычно multiple of 32;
;              max one chunk = 32, если non-multiple)
;          BgRamH / BgRamL = destination RAM_G address (будет продвинут)
;   Клобает: AF, BC, DE, HL, BgRamH, BgRamL
ZiFi_StreamSection:
.Loop:          LD   A, D
                OR   E
                RET  Z
                ; chunk size = min(32, DE)
                LD   A, D
                OR   A
                JR   NZ, .Full           ; DE >= 256 → использовать full 32
                LD   A, E
                CP   32
                JR   NC, .Full
                ; partial: B = E sectors, byte count = E * 512
                LD   B, E
                LD   H, E
                LD   L, 0
                ADD  HL, HL              ; HL = byte count = E * 512
                LD   (ZiFi_StreamByteCount), HL
                XOR  A
                LD   E, A                ; DE = 0 после этой iteration
                JR   .Read
.Full:          LD   B, 32
                LD   HL, 16384
                LD   (ZiFi_StreamByteCount), HL
                LD   HL, -32
                ADD  HL, DE
                EX   DE, HL              ; DE = DE - 32
.Read:          LD   (ZiFi_StreamRemaining), DE
                ; прочитать B sectors в buffer page #03 @ #0000 (slot-0 view)
                LD   C, ZIFI_BUFFER_PAGE
                LD   HL, #0000
                CALL ZiFi_Load512
                LD   A, TSLibPage
                SetPage0_A
                LD   A, ZIFI_BUFFER_PAGE
                SetPage2_A
                LD   BC, (ZiFi_StreamByteCount)
                LD   HL, #8000
                LD   A, (BgRamH)
                LD   DE, (BgRamL)
                CALL FT.WriteMem
                ; advance BgRamL/H by byte count
                LD   HL, (ZiFi_StreamByteCount)
                LD   DE, (BgRamL)
                ADD  HL, DE
                LD   (BgRamL), HL
                JR   NC, .NoCy
                LD   A, (BgRamH)
                INC  A
                LD   (BgRamH), A
.NoCy:          LD   DE, (ZiFi_StreamRemaining)
                JR   .Loop

; Выделять внутри Core module, чтобы bytes попадали в Core.bin и были защищены
; от MMU/TSLib runtime overwrites. EQU на адреса вне Core block оставлял их в
; случайной/unmapped memory.
ZiFi_StreamByteCount: DEFW 0
ZiFi_StreamRemaining: DEFW 0
ZiFi_BgDstPage:       DEFB 0

; OVL_GS_InitAndStartMenuMusic — обнаружить General Sound, один раз загрузить
; ZUMAAUD.PAK, затем запустить module как menu/level-select/more-games music.
OVL_GS_InitAndStartMenuMusic:
                LD   A, (GS_MenuMusicLoaded)
                OR   A
                JR   Z, .needLoad
                JP   GS_PlayMenuMusic
.needLoad:      CALL GS_Detect
                JR   C, .gsDetected
                RET
.gsDetected:    LD   A, 1
                LD   (GS_Present), A
                LD   (GS_MenuMusicHandle), A
                XOR  A
                LD   (GS_SfxLoaded), A
                CALL GS_QueryRamPages
                CALL GS_InitFxMixer
                CALL ZiFi_Init
                JR   NC, .sdFail
                CALL ZiFi_AudioPakOpen
                JR   NC, .sdDoneFail
                CALL GS_CacheAudioPakToRam
                JR   NC, .sdDoneFail
                CALL ZiFi_Done
                DI
                LD   A, #30                         ; Load Module
                CALL GS_SendCommandOverlay
                RET  NC
                LD   A, #D1                         ; Open Stream
                CALL GS_SendCommandOverlay
                RET  NC
                CALL GS_StreamAudioCacheToDevice    ; стрим RAM->GS + тик прогресс-бара
                JR   NC, .closeFail
                LD   A, #D2                         ; Close Stream
                CALL GS_SendCommandOverlay
                RET  NC
                CALL GS_ReadHandleMaybe
                LD   A, 1
                LD   (GS_MenuMusicLoaded), A
                CALL GS_PostLoadSettle              ; пауза перед командой включения музыки
                JP   GS_PlayMenuMusic
.closeFail:     LD   A, #D2
                CALL GS_SendCommandOverlay
                RET
.sdDoneFail:    CALL ZiFi_Done
.sdFail:        RET

