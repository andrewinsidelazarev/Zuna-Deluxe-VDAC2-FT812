                LD   H, (IX+5)
                LD   (VDC_TrackSamples1), HL
                LD   A, (IX+6)
                LD   (VDC_TrackPageCount1), A
                LD   L, (IX+7)
                LD   H, (IX+8)
                LD   (VDC_TrackSamples2), HL
                LD   A, (IX+9)
                LD   (VDC_TrackPageCount2), A

