                ; bg: pages #07..#0E -> BG_RAMG (по 16K), как fallback.
                LD   HL, BG_RAMG_ADDR & #FFFF
                LD   (BgRamL), HL
                LD   A, (BG_RAMG_ADDR >> 16) & #FF
                LD   (BgRamH), A
                LD   A, #07
                LD   (RawPak_StgPage), A
                LD   B, 8
.ftBgPage:      PUSH BC
                LD   A, (RawPak_StgPage)
                SetPage2_A
                LD   HL, #8000
                LD   BC, 16384
                LD   A, (BgRamH)
                LD   DE, (BgRamL)
                CALL FT.WriteMem
                CALL RawPak_VerifyRamG16KPage
                JP   NC, .ftBgVerifyErr
                LD   HL, (BgRamL)
                LD   DE, #4000
                ADD  HL, DE
                LD   (BgRamL), HL
                JR   NC, .ftNoCy
                LD   A, (BgRamH)
                INC  A
                LD   (BgRamH), A
.ftNoCy:        LD   A, (RawPak_StgPage)
                INC  A
                LD   (RawPak_StgPage), A
                POP  BC
                DJNZ .ftBgPage
                LD   A, 4
                if RUNTIME_DIAGNOSTICS_ENABLED
                LD   (ZiFiTraceStep), A
                endif

                ; palette: page #03 -> BG_PALETTE_RAMG (512 bytes).
                LD   A, ZIFI_BUFFER_PAGE
                SetPage2_A
                LD   HL, #8000
                LD   BC, 512
                LD   A, (BG_PALETTE_RAMG >> 16) & #FF
                LD   DE, BG_PALETTE_RAMG & #FFFF
                CALL FT.WriteMem
                CALL RawPak_VerifyGameplayPaletteRamG
                JP   NC, .Err
                LD   A, 6
                if RUNTIME_DIAGNOSTICS_ENABLED
                LD   (ZiFiTraceStep), A
                endif

                ; bg/palette uploaded в RAM_G, track staged в page #06.
.Ok:            SCF
                PUSH AF
                CALL ZiFi_Done
                POP  AF
                RET
.Err:           OR   A                                  ; CF=0: caller must treat as failed load
                PUSH AF
                CALL ZiFi_Done
                POP  AF
                RET
.InitErr:       CALL ZiFi_Done
                OR   A
                RET
.ftBgVerifyErr:
                POP  BC
                JP   .Err

; LoadLevelFromPack_Setup — открыть ZUMALVL.PAK и загрузить TOC entry CurrentLevel
; в ZiFi_LevelTOC.
;   Выход: CF=1 ok, CF=0 error
LoadLevelFromPack_Setup:
                CALL ZiFi_Init
                JR   NC, .InitErr
                CALL ZiFi_PakOpen
                JR   NC, .Err
                LD   A, (CurrentLevel)
                CALL ZiFi_PakReadToc
.Err:           PUSH AF
                CALL ZiFi_Done
                POP  AF
                RET
.InitErr:       CALL ZiFi_Done
                OR   A
                RET

; OVL_LoadLevelSelectPreviewAssets — stream preview thumbnail выбранного level
; (raw ARGB4, 306x196 padded to 8x16K pages) из ZUMALVL.PAK в выбранный
; LevelSelectPreviewLoadRam*. Level-select использует ping-pong RAM_G buffers,
; чтобы не перезаписывать bitmap, который ещё referenced текущим display list.
; Вход через resident LoadLevelSelectPreviewAssets trampoline: slot 3 держит
; LOADER_OVL_PAGE, trampoline восстанавливает PAGE3=#04 и управляет interrupts,
; поэтому routine НЕ должна трогать slot 3. SD и FT phases держим раздельно:
; FT812 и SD делят Z-Controller SPI bus. Выход: CF=1 ok / CF=0.
OVL_LoadLevelSelectPreviewAssets:
                CALL ZiFi_Init
                JP   NC, .err_init
                CALL ZiFi_PakOpen
                JP   NC, .err
                LD   A, (CurrentLevel)
                CP   LEVEL_RUNTIME_COUNT
                JR   C, .idx_ok
                XOR  A
.idx_ok:        CALL ZiFi_PakReadToc
                JP   NC, .err
                ; Требовать ровно canonical raw thumbnail size.
                LD   HL, (ZiFi_LevelTOC + 18)           ; preview_size
                LD   A, H
                CP   1
                JP   NZ, .err
                LD   A, L
                OR   A                                  ; 8 pages * 32 sectors = #0100
                JP   NZ, .err
                ; SD phase: preview_off -> pages #07..#0E.
                LD   HL, (ZiFi_LevelTOC + 16)           ; preview_off
                LD   (RawPak_LogCur), HL
                LD   A, #07
                LD   (RawPak_StgPage), A
                LD   B, 8
.sd_page:       PUSH BC
                LD   A, (RawPak_StgPage)
                SetPage2_A
                LD   IX, #8000
                LD   B, 32
.sd_sec:        PUSH BC
                CALL RawPak_ReadOneLogicalIX_Retry
                JR   C, .sd_read_err
                LD   DE, 512
                ADD  IX, DE
                POP  BC
                DJNZ .sd_sec
                LD   A, (RawPak_StgPage)
                INC  A
                LD   (RawPak_StgPage), A
                POP  BC
                DJNZ .sd_page
                CALL LevelSelectPreviewValidateStaged
                JP   NC, .err
                ; FT phase: pages #07..#0E -> selected preview RAM_G buffer.
                ; BgRamL/H подготовлены resident trampoline до того, как ZiFi мапит
                ; slot0 на driver page.
                LD   A, #07
                LD   (RawPak_StgPage), A
                LD   B, 8
.ft_page:       PUSH BC
                LD   A, (RawPak_StgPage)
                SetPage2_A
                LD   HL, #8000
                LD   BC, 16384
                LD   A, (BgRamH)
                LD   DE, (BgRamL)
                CALL FT.WriteMem
                CALL RawPak_VerifyRamG16KPage
                JR   NC, .ft_readback_err
                LD   HL, (BgRamL)
                LD   DE, #4000
                ADD  HL, DE
                LD   (BgRamL), HL
                JR   NC, .ft_no_carry
                LD   A, (BgRamH)
                INC  A
                LD   (BgRamH), A
.ft_no_carry:   LD   A, (RawPak_StgPage)
                INC  A
                LD   (RawPak_StgPage), A
                POP  BC
                DJNZ .ft_page
                CALL SetCurrentTrackPage
                CALL ZiFi_Done
                SCF
                RET
.ft_readback_err:
                POP  BC
                JR   .err
.sd_read_err:   POP  BC
                POP  BC
.err:           CALL ZiFi_Done
.err_init:      CALL SetCurrentTrackPage
                OR   A
                RET

LevelSelectPreviewValidateStaged:
                LD   A, #07
                SetPage2_A
                LD   HL, #8000
                LD   B, 16
                XOR  A
.vpv_loop:      OR   (HL)
                INC  HL
                DJNZ .vpv_loop
                JR   Z, .vpv_fail
                SCF
                RET
.vpv_fail:      OR   A
                RET

RawPak_VerifyRamG16KPage:
                LD   HL, #8000
                LD   DE, (BgRamL)
                LD   A, (BgRamH)
                CALL RawPak_VerifyRamG16
                RET  NC
                LD   HL, (BgRamL)
                LD   DE, #3FF0
                ADD  HL, DE
                EX   DE, HL
                LD   A, (BgRamH)
                JR   NC, .tail_no_carry
                INC  A
.tail_no_carry: LD   HL, #BFF0
                JP   RawPak_VerifyRamG16

RawPak_VerifyGameplayPaletteRamG:
                LD   HL, #8000
                LD   DE, BG_PALETTE_RAMG & #FFFF
                LD   A, (BG_PALETTE_RAMG >> 16) & #FF
                CALL RawPak_VerifyRamG16
                RET  NC
                LD   HL, #81F0
                LD   DE, (BG_PALETTE_RAMG + #01F0) & #FFFF
                LD   A, ((BG_PALETTE_RAMG + #01F0) >> 16) & #FF
                JP   RawPak_VerifyRamG16

RawPak_VerifyRamG16:
                LD   (RawPak_VerifySrc), HL
                LD   (RawPak_VerifyRamL), DE
                LD   (RawPak_VerifyRamH), A
                LD   HL, RawPak_ReadbackBuf
                LD   BC, 16
                LD   A, (RawPak_VerifyRamH)
                LD   DE, (RawPak_VerifyRamL)
                CALL FT.ReadMem
                LD   HL, RawPak_ReadbackBuf
                LD   DE, (RawPak_VerifySrc)
                LD   B, 16
.vrg_loop:      LD   A, (DE)
                CP   (HL)
                JR   NZ, .vrg_fail
                INC  DE
                INC  HL
                DJNZ .vrg_loop
                SCF
                RET
.vrg_fail:      OR   A
                RET

                include "loading_screen_ovl40.inc"     ; LOADING LEVEL X-X (перенос из page 0, 1024-порт)
