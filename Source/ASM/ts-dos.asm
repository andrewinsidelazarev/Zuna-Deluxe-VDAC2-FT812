                ; 16K page после Track V2 pages. Runtime мапит её в #13.
                LD   A, (IX+13) : CP #5A : JP NZ, .Err  ; 'Z'
                LD   A, (IX+14) : CP #42 : JP NZ, .Err  ; 'B'
                LD   A, (IX+15) : CP #54 : JP NZ, .Err  ; 'T'
                LD   A, (IX+16) : CP #31 : JP NZ, .Err  ; '1'
                LD   A, (IX+17)
                CP   1
                JP   NZ, .Err
                LD   (BulletTrajPageCount), A

