; На выходе пак готов к Fat_ReadSectors/RawPak_ReadOneLogicalIX с любого сектора.
; CF=1 при успехе, CF=0 — пак не найден или ошибка.
ZiFi_PakOpen:
                LD   A, FAT_ID_LVL
                LD   HL, RAWPAK_NAME_PAK
                JR   ZiFi_OpenPak
