; ---------------------------------------------------------------------
; ZiFi_Init — поднять SD driver для session file I/O calls.
;   DI, slot 0 = #0F (driver page), DOS_SWP, DEV_INI, HDD, SETROOT.
; После Init entries ZiFi at #2002..#2070 можно вызывать напрямую.
;   CF=1 при успехе, CF=0 при init error. После успешного init всё равно
;   нужно вызвать ZiFi_Done.
ZiFi_Init:
                DI
                ; FT812 и SD на ОДНОЙ SPI-шине Z-Controller (рег #77). Перед началом
                ; SD-сессии ЯВНО снимаем CS FT812 (#77 = SPI_FT_CS_OFF = #03), иначе,
                ; если перед этим по шине работал FT812 (boot loading screen), он
                ; остаётся владельцем шины и первое SD-обращение срывается.
                LD   BC, #0077
                LD   A, #03
                OUT  (C), A
                LD   BC, #0057
                LD   A, #FF
                OUT  (C), A
                LD   A, TSLibPage
                SetPage0_A                     ; slot 0 вернуть на штатную TSLib page до SD-session
                CALL sd_init                   ; внутренний контракт: CF=0 ready, CF=1 recovery failed
                JR   C, .Err                   ; не выдавать ложный успех вызывающему loader'у
                SCF                            ; публичный ZiFi-контракт наоборот: CF=1 означает success
                RET
.Err:           OR   A                         ; публичный ZiFi-контракт: CF=0 означает init error
                RET

; ZiFi_Done — восстановить TSLib в slot 0, EI.
ZiFi_Done:
                LD   BC, #0077
                LD   A, #03
                OUT  (C), A
                LD   BC, #0057
                LD   A, #FF
                OUT  (C), A
                LD   A,  TSLibPage
                SetPage0_A
                EI
                RET

; Backwards-compat aliases: старые wrappers ниже рассчитаны на per-call swap.
; Теперь ZiFi_Init/ZiFi_Done вызываются на границе session, поэтому здесь
; достаточно RET — slot-0 mapping уже #0F.
ZiFi_Enter:     RET
ZiFi_Leave:     RET

; ---------------------------------------------------------------------
; ZiFi_FEntry — поиск filename в current dir.
;   Вход : HL → {flag, name, 0}
;   Выход: Z=не найдено; NZ=найдено, [DE:HL]=size; SEEK0 вызывается автоматически
ZiFi_FEntry:
                CALL ZiFi_Enter
                CALL ZIFI_FENTRY
                ; сохранить result flags + DE/HL через Leave
                PUSH AF
                PUSH HL
                PUSH DE
                CALL ZiFi_Leave
                POP  DE
                POP  HL
                POP  AF
                RET

; ZiFi_Load512 — прочитать B 512-byte blocks из current file в (C:HL).
;   Вход : C=dest page, HL=offset (#0000..#3FFF slot-0 view), B=blocks
;   Выход: CHL продвинут; A=#0F если end-of-chain
ZiFi_Load512:
                JP   RawPak_ReadSectors

; ZiFi_LoadNon — пропустить B sectors (seek forward).
;   Вход : B=sectors
ZiFi_LoadNon:
                JP   RawPak_SkipB

; ZiFi_Seek0 — перемотать current file на offset 0.
ZiFi_Seek0:
                JP   RawPak_Seek0

; ZiFi_SetDir — chdir в directory, найденную предыдущим FEntry.
ZiFi_SetDir:
                CALL ZiFi_Enter
                CALL ZIFI_SETDIR
                CALL ZiFi_Leave
                RET

; ZiFi_SetRoot — chdir в /.
ZiFi_SetRoot:
                CALL ZiFi_Enter
                CALL ZIFI_SETROOT
                CALL ZiFi_Leave
                RET

